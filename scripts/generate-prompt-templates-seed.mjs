/**
 * 从 comic-generator-decompiled 的云端模板 JSON 生成内置 seed 文件。
 * 用法: node scripts/generate-prompt-templates-seed.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const JSON_PATH = path.resolve(
  ROOT,
  '../comic-generator-decompiled/docs/_tmp_prompts.json',
)
const OUT_PATH = path.resolve(ROOT, 'src/lib/storage/prompt-templates-seed.ts')

const SETTINGS_TYPES = ['extract', 'style', 'storyboard']

function escapeTemplate(str) {
  return str.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
}

function toPromptTemplate(item) {
  const promptType = item.prompt_type
  if (!SETTINGS_TYPES.includes(promptType)) return null

  const key = String(item.key ?? '').trim()
  const name = String(item.name ?? key).trim()
  const content = String(item.value ?? '').trim()
  const description = String(item.description ?? '').trim()
  const isBuiltin = Boolean(item.is_builtin)
  const id = `seed-${promptType}-${key.replace(/[^a-zA-Z0-9_-]/g, '_')}`

  const fields = [
    `id: '${id}'`,
    `key: ${JSON.stringify(key)}`,
    `name: ${JSON.stringify(name)}`,
    `promptType: '${promptType}'`,
    `content: \`${escapeTemplate(content)}\``,
    `isBuiltin: ${isBuiltin}`,
  ]
  if (description) {
    fields.push(`description: ${JSON.stringify(description)}`)
  }

  return `  {\n    ${fields.join(',\n    ')},\n  }`
}

function main() {
  if (!fs.existsSync(JSON_PATH)) {
    console.error(`Missing source JSON: ${JSON_PATH}`)
    process.exit(1)
  }

  const raw = JSON.parse(fs.readFileSync(JSON_PATH, 'utf8'))
  const items = (raw.data ?? []).filter((i) => SETTINGS_TYPES.includes(i.prompt_type))
  items.sort((a, b) => {
    const ta = a.prompt_type.localeCompare(b.prompt_type)
    if (ta !== 0) return ta
    return (a.sort_order ?? 0) - (b.sort_order ?? 0) || (a.id ?? 0) - (b.id ?? 0)
  })

  const grouped = Object.fromEntries(SETTINGS_TYPES.map((t) => [t, []]))
  for (const item of items) {
    const tpl = toPromptTemplate(item)
    if (tpl) grouped[item.prompt_type].push(tpl)
  }

  const header = `// Copyright (c) 2026 local-creator contributors.
// AUTO-GENERATED by scripts/generate-prompt-templates-seed.mjs — do not edit manually.
// Source: comic-generator-decompiled/docs/_tmp_prompts.json

import type { PromptTemplate } from '@/types/settings'

`

  const body = SETTINGS_TYPES.map((type) => {
    const constName =
      type === 'extract'
        ? 'SEED_EXTRACT_TEMPLATES'
        : type === 'style'
          ? 'SEED_STYLE_TEMPLATES'
          : 'SEED_STORYBOARD_TEMPLATES'
    const list = grouped[type]
    return `export const ${constName}: PromptTemplate[] = [\n${list.join(',\n')},\n]`
  }).join('\n\n')

  const footer = `

export const SEED_PROMPT_TEMPLATES = {
  extract: SEED_EXTRACT_TEMPLATES,
  style: SEED_STYLE_TEMPLATES,
  storyboard: SEED_STORYBOARD_TEMPLATES,
} as const

export type SeedPromptType = keyof typeof SEED_PROMPT_TEMPLATES
`

  fs.writeFileSync(OUT_PATH, header + body + footer, 'utf8')
  console.log(`Written ${OUT_PATH} (${items.length} templates)`)
  for (const type of SETTINGS_TYPES) {
    const list = grouped[type]
    const builtin = items.filter((i) => i.prompt_type === type && i.is_builtin).length
    console.log(`  ${type}: ${list.length} (${builtin} builtin)`)
  }
}

main()
